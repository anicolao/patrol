export function recordingFfmpegArgs({ streamUrl, segmentSeconds, outputPattern }) {
  return [
    '-hide_banner',
    '-nostdin',
    '-loglevel',
    'warning',
    '-rtsp_transport',
    'tcp',
    '-i',
    streamUrl,
    '-map',
    '0:v:0',
    '-map',
    '0:a?',
    '-c:v',
    'copy',
    '-c:a',
    'aac',
    '-b:a',
    '64k',
    '-f',
    'segment',
    '-segment_format',
    'mp4',
    '-segment_time',
    String(segmentSeconds),
    '-segment_list',
    'pipe:1',
    '-segment_list_type',
    'csv',
    '-segment_list_flags',
    '+live',
    '-reset_timestamps',
    '1',
    outputPattern
  ];
}
